/* Turns a spritesheet into a run of text sprites — the animated sibling of
 * `sprite-from-png.mjs`, which handles single drawings.
 *
 *   node prototype/screen/sheet-to-frames.mjs art/reaction.png \
 *        --grid 5x2 --frames 10 --size 28x40 --out reaction-frames.js
 *
 * Why text rather than blitting the sheet at runtime: the Screen has exactly four
 * tones (screen.js:61) and the Unit ships no binary assets (ADR-0004). Converting
 * once, here, gets both — plus integer scaling and no smoothing by construction,
 * since `drawSprite` paints whole `fillRect` blocks.
 *
 * Every frame is cut against **frame 0's bounding box**, not its own. Trimming each
 * frame independently re-centres her a pixel at a time, and this animation is a
 * head-tilt and a blink — per-frame trim would eat exactly the motion it is for.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { decodePng } from './png.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const argv = process.argv.slice(2)
const file = argv.find(a => !a.startsWith('--'))
const flag = (n, d) => { const i = argv.indexOf('--' + n); return i < 0 ? d : argv[i + 1] }
if (!file) { console.error('usage: sheet-to-frames.mjs <sheet.png> [--grid 5x2] [--frames 10] [--size 28x40] [--out reaction-frames.js]'); process.exit(1) }

const [COLS, ROWS] = flag('grid', '5x2').split('x').map(Number)
const COUNT = Number(flag('frames', String(COLS * ROWS)))
const [TW, TH] = flag('size', '28x40').split('x').map(Number)
const OUT = flag('out', 'reaction-frames.js')

const img = decodePng(readFileSync(file))
const FW = img.width / COLS, FH = img.height / ROWS
if (!Number.isInteger(FW) || !Number.isInteger(FH))
  throw new Error(`${img.width}x${img.height} does not divide into a ${COLS}x${ROWS} grid`)

const TONES = [['#', 227.1], ['-', 131.8], ['=', 89.9], ['o', 10.6]]
const lum = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b
const tone = L => TONES.reduce((b, t) => Math.abs(L - t[1]) < Math.abs(L - b[1]) ? t : b)[0]
const at = (x, y) => { const o = (y * img.width + x) * 4; return img.data.subarray(o, o + 4) }
const origin = i => [(i % COLS) * FW, ((i / COLS) | 0) * FH]

function bbox(i) {
  const [ox, oy] = origin(i)
  let x0 = 1e9, y0 = 1e9, x1 = -1, y1 = -1
  for (let y = 0; y < FH; y++) for (let x = 0; x < FW; x++)
    if (at(ox + x, oy + y)[3] >= 128) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y }
  if (x1 < 0) throw new Error('frame ' + i + ' is entirely transparent')
  return { x0, y0, w: x1 - x0 + 1, h: y1 - y0 + 1 }
}

const B = bbox(0)                       /* the shared box — see the header */
function convert(i) {
  const [ox, oy] = origin(i)
  const rows = []
  for (let ty = 0; ty < TH; ty++) {
    let line = ''
    for (let tx = 0; tx < TW; tx++) {
      const ax = Math.floor(tx * B.w / TW), bx = Math.max(Math.floor((tx + 1) * B.w / TW), ax + 1)
      const ay = Math.floor(ty * B.h / TH), by = Math.max(Math.floor((ty + 1) * B.h / TH), ay + 1)
      let R = 0, G = 0, Bl = 0, A = 0, n = 0
      for (let y = ay; y < by; y++) for (let x = ax; x < bx; x++) {
        const p = at(ox + B.x0 + x, oy + B.y0 + y), w = p[3] / 255
        R += p[0] * w; G += p[1] * w; Bl += p[2] * w; A += p[3]; n++
      }
      const alpha = n ? A / n : 0
      let ch = '.'
      if (alpha >= 128) { const ws = A / 255; ch = ws > 0 ? tone(lum(R / ws, G / ws, Bl / ws)) : 'o' }
      line += ch
    }
    rows.push(line)
  }
  return rows
}

const frames = []
for (let i = 0; i < COUNT; i++) frames.push(convert(i))

/* How much actually moves, per frame, against the idle. A frame that differs from
   frame 0 by nothing is a frame that was lost in the quantise. */
const diff = f => f.reduce((n, row, y) => n + [...row].filter((c, x) => c !== frames[0][y][x]).length, 0)
console.log(`${file}\n  ${img.width}x${img.height} → ${COLS}x${ROWS} grid, ${COUNT} frames of ${FW}x${FH}`)
console.log(`  figure bbox (frame 0): ${B.w}x${B.h} at ${B.x0},${B.y0} → ${TW}x${TH}`)
frames.forEach((f, i) => console.log(`  frame ${String(i).padStart(2)}: ${String(diff(f)).padStart(4)} of ${TW * TH} cells differ from idle`))

const body = frames.map((f, i) =>
  `  /* ${i}${i === 0 ? ' — idle' : ''} */\n  [\n${f.map(r => `    '${r}',`).join('\n')}\n  ],`).join('\n')

writeFileSync(resolve(here, OUT), `/* Generated by sheet-to-frames.mjs — do not hand-edit.
   Source: ${file.split('/').pop()} (${COLS}x${ROWS} grid, ${FW}x${FH} per frame)

   Ten frames of the Wizard reacting to a Deck being turned: she raises her brows,
   smiles, tilts her head, blinks once, and settles. Frame 0 is the idle she rests
   on; 1..9 play once and hand back to 0.

   Four tones, ${TW}x${TH}, same grammar as \`drawn.js\` — '#' lit, '-' half-light,
   '=' shadow, 'o' black, '.' transparent. */

export const REACTION_FRAMES = [
${body}
]

export const REACTION_IDLE = 0
export const REACTION_W = ${TW}
export const REACTION_H = ${TH}
`)
console.log(`\n  wrote ${OUT} — ${COUNT} frames`)
